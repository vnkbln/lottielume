"""Regenerate checked-in FFGL thumbnail pixels from the user PNGs (Pillow)."""
from pathlib import Path
from PIL import Image
root = Path(__file__).resolve().parents[1]
for kind in ("Player", "Emitter"):
    source = root / "assets" / "icons" / f"Lottie_{kind}.png"
    im = Image.open(source).convert("RGBA")
    if im.size != (160, 120):
        raise ValueError(f"Unexpected thumbnail dimensions: {source}")
    pixels = [int.from_bytes(bytes(p), "big") for p in im.get_flattened_data()]
    lines = ["// Generated by scripts/embed-thumbnails.py; top-left origin, 0xRRGGBBAA.",
             "static const FFUInt32 thumbnailPixels[] = {"]
    lines += ["    " + ", ".join(f"0x{p:08x}u" for p in pixels[i:i+8]) + "," for i in range(0,len(pixels),8)]
    lines += ["};", ""]
    (root / "src" / f"Thumbnail{kind}.inc").write_text("\n".join(lines), encoding="utf-8")
